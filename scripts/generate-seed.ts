/**
 * Generates supabase/seed.sql from the TypeScript catalog (single source of truth).
 *   npm run db:seed-sql
 */
import fs from "node:fs";
import path from "node:path";
import { CHAINS } from "../src/lib/catalog/chains";
import { MARKETS } from "../src/lib/catalog/markets";
import { CATALOG_ITEMS } from "../src/lib/catalog/menu";

const q = (v: unknown): string => {
  if (v == null) return "null";
  if (typeof v === "number") return String(v);
  if (typeof v === "boolean") return v ? "true" : "false";
  if (Array.isArray(v)) return `array[${v.map(q).join(",")}]::text[]`;
  if (typeof v === "object") return `${q(JSON.stringify(v))}::jsonb`;
  return `'${String(v).replace(/'/g, "''")}'`;
};

const lines: string[] = [
  "-- GENERATED by scripts/generate-seed.ts — do not edit by hand.",
  "-- Markets, chain catalog and chain-wide menu items. Prices are ESTIMATES (price_status = 'estimate').",
  "begin;",
];

for (const m of MARKETS) {
  lines.push(
    `insert into public.markets (id,name,timezone,bbox_south,bbox_west,bbox_north,bbox_east,center_lat,center_lng,tax_rate,active) values (${[
      m.id, m.name, m.timezone, ...m.bbox, m.center.lat, m.center.lng, m.taxRate, m.active,
    ].map(q).join(",")}) on conflict (id) do update set name=excluded.name, timezone=excluded.timezone, tax_rate=excluded.tax_rate;`,
  );
}

for (const c of CHAINS) {
  lines.push(
    `insert into public.chains (id,slug,name,tier,priority,wikidata,aliases,website,direct_order_url,categories,price_level,source) values (${[
      c.id, c.slug, c.name, c.tier, c.priority, c.wikidata, c.aliases, c.website, c.directOrderUrl, c.categories, c.priceLevel, "catalog",
    ].map(q).join(",")}) on conflict (id) do update set name=excluded.name, tier=excluded.tier, priority=excluded.priority, wikidata=coalesce(public.chains.wikidata, excluded.wikidata), aliases=excluded.aliases, website=excluded.website, direct_order_url=excluded.direct_order_url, categories=excluded.categories;`,
  );
}

for (const m of CATALOG_ITEMS) {
  const cols = {
    catalog_key: m.id,
    chain_id: m.chainId,
    name: m.name,
    description: m.description,
    category: m.category,
    ingredients: m.ingredients,
    is_combo: m.isCombo,
    price_low: m.price.low,
    price_high: m.price.high,
    price_status: m.price.status,
    price_channel: m.price.channel,
    combo_price_low: m.comboPrice?.low ?? null,
    combo_price_high: m.comboPrice?.high ?? null,
    combo_price_status: m.comboPrice?.status ?? "unknown",
    portion_size: m.portion.size,
    nutrition: m.nutrition ?? null,
    source: "catalog",
    verification: m.provenance.verification,
  };
  const entries = cols;
  lines.push(
    `insert into public.menu_items (${Object.keys(entries).join(",")}) values (${Object.values(entries).map(q).join(",")}) on conflict (catalog_key) do update set name=excluded.name, description=excluded.description, category=excluded.category, ingredients=excluded.ingredients, price_low=case when public.menu_items.price_status='estimate' then excluded.price_low else public.menu_items.price_low end, price_high=case when public.menu_items.price_status='estimate' then excluded.price_high else public.menu_items.price_high end, portion_size=excluded.portion_size;`,
  );
}

lines.push("commit;", "");
const out = path.join(__dirname, "..", "supabase", "seed.sql");
fs.writeFileSync(out, lines.join("\n"));
console.log(`Wrote ${out}: ${MARKETS.length} markets, ${CHAINS.length} chains, ${CATALOG_ITEMS.length} menu items`);
